//! SHA-256 (FIPS 180-4), HMAC-SHA-256 (RFC 2104) and hex helpers.
//!
//! The store uses SHA-256 for content addressing and integrity checks and
//! HMAC-SHA-256 for the keyed "hash of hash" recorded for sensitive files.
//! The implementation is deliberately small and dependency free; it is checked
//! against the FIPS 180-4 and RFC 4231 test vectors in the unit tests. It is
//! not constant time, which is irrelevant for the way it is used here (no
//! secret-dependent branching on attacker-observable timing).
#![allow(clippy::indexing_slicing)] // fixed-size arrays indexed by bounded loop counters

/// A 32-byte digest.
pub type Digest = [u8; 32];

